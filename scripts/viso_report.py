"""Aggregate run directories into a results markdown table (calls the frozen vivqa_s1_v2 metrics).
    python scripts/viso_report.py --runs A0=output/viso/flat A2=output/viso/viso_soft:pertype --out report.md [--split test]
Each run spec is NAME=RUN_DIR[:VARIANT]; VARIANT is a calibration variant (uncal | pertype | global | softtype) read from
RUN_DIR/calibration/preds_<split>_<variant>.jsonl, or omitted to read RUN_DIR/preds_<split>.jsonl (temperature-free).
Gold is vivqa_s1_v2/data/<split>.jsonl restricted to the ids of the predictions file. Only generated files are quoted.
--view {all,core,image_unseen} [--flags PATH] (v1.1 release) restricts the gold to a test view defined by the benchmark's
s1bench/flags.py (see viso_bootstrap.py); the default (all) output is unchanged."""
import argparse
import json
import os
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, REPO)

from utils.viso_s1 import read_jsonl  # noqa: E402
from s1bench.metrics import evaluate  # noqa: E402


def fmt(x):
    return "-" if x is None or x != x else f"{x:.4f}"


# ----------------------------------------------------------------------------------------- results.md (Kaggle runs)
def ms(d, nd=4):
    if not d or d.get("mean") is None:
        return "-"
    return f"{d['mean']:.{nd}f}" + ("" if d.get("std") is None else f" ± {d['std']:.{nd}f}") + (f" (n={d['n']})" if d["n"] > 1 else "")


def static_efficiency(args, manifest):
    """Parameters and batch-1 FLOPs of ViSO and FlatS1 (CPU, no timing: latency is measured later on the user's CPU)."""
    import warnings
    warnings.filterwarnings("ignore")
    import torch
    import data_utils.vocabs.s1_vocab  # noqa: F401
    import models.viso  # noqa: F401
    from builders.model_builder import build_model
    from builders.vocab_builder import build_vocab
    from train_viso import load_config
    from utils import viso_efficiency as E
    out = {}
    bases = {"ViSO": "configs/viso_vivqav2.yaml", "FlatS1": "configs/viso_flat_vivqav2.yaml"}
    for j in manifest["jobs"]:                                  # the configs of the manifest (SigLIP 2 manifests use configs/viso_siglip2.yaml / viso_flat_siglip2.yaml)
        bases["FlatS1" if "flat" in j["base_config"] else "ViSO"] = j["base_config"]
    for arch, base in bases.items():
        cfg = load_config(os.path.join(args.code_root, base), ["MODEL.DEVICE", "cpu", "DATASET.VOCAB.S1_DIR", os.path.join(args.s1_dir, "data")])
        torch.manual_seed(0)
        vocab = build_vocab(cfg.DATASET.VOCAB)
        model = build_model(cfg.MODEL, vocab)
        n_reg, d_feat, use_boxes = E.input_shape(cfg.MODEL)
        out[arch] = {"params": E.param_counts(model), "flops_batch1": E.forward_flops(model, E.make_batch(vocab, n_regions=n_reg, d_feature=d_feat, boxes=use_boxes,
                                                                                                                 cached_text=cfg.MODEL.TEXT_EMBEDDING.ARCHITECTURE == "CachedBertEmbedding"))}
    return out


def results_markdown(out_dir, manifest, boot, eff, s1_data):
    """results.md: overall / per type / S1-Human / calibration / escalation / paired comparisons / efficiency."""
    L = ["# ViSO on ViVQA-S1: results (generated by scripts/viso_report.py from the run outputs)", ""]
    if "methods" not in boot:
        return "\n".join(L + ["No predictions found.", ""])
    L += [f"Test items: {boot['n_items']} (S1-Human: {boot['n_human_items']}); bootstrap: {boot['resamples']} resamples, seed {boot['seed']}. "
          "Cells are mean ± std over seeds (n = number of seeds).", ""]
    if boot.get("view"):                      # only present when a view / flags file was requested (default output is unchanged)
        exc = ", ".join(f"{k} {v}" for part in boot["excluded_by_flag"].values() for k, v in part.items())
        L += [f"View: **{boot['view']}** ({boot['n_gold_view']} of {boot['n_gold_split']} gold items; scored n = {boot['n_items']}); "
              f"flags `{boot['flags_file']}` sha256 `{boot['flags_sha256']}`; excluded by flag: {exc}.", ""]
    names = list(manifest["methods"])
    L += ["## Overall (primary metrics, all items vs gold_label)", "", "| method | accuracy | NLL | Brier | ECE | AURC |", "|---|---|---|---|---|---|"]
    for m in names:
        if m in boot["methods"]:
            d = boot["methods"][m]["mean_std"]
            L.append(f"| {m} | " + " | ".join(ms(d[k]) for k in ("accuracy", "nll", "brier", "ece", "aurc")) + " |")
    L += ["", "## Per type (accuracy / NLL, mean over seeds)", "", "| method | noul acc | score acc | choice acc | noul NLL | score NLL | choice NLL |", "|---|---|---|---|---|---|---|"]
    for m in names:
        if m not in boot["methods"]:
            continue
        ev = [v["evaluate"]["primary"] for v in boot["methods"][m]["seeds"].values()]
        cell = lambda t, k: ms(mean_std_vals([e[t][k] for e in ev if t in e]))
        L.append(f"| {m} | " + " | ".join(cell(t, "accuracy") for t in ("noul", "score", "choice")) + " | " + " | ".join(cell(t, "nll") for t in ("noul", "score", "choice")) + " |")
    L += ["", "## S1-Human (strict human10 items; soft metrics)", "", "| method | soft accuracy | Brier (soft) | KL(gold‖pred) |", "|---|---|---|---|"]
    for m in names:
        if m in boot["methods"]:
            d = boot["methods"][m]["mean_std"]
            L.append(f"| {m} | " + " | ".join(ms(d[k]) for k in ("soft_accuracy", "brier_soft", "kl")) + " |")
    L += ["", "## Paired comparisons (A − B; mean ± std over seeds of the point difference; 95% bootstrap CI of the first seed)", "",
          "| comparison | Δ accuracy | Δ NLL | Δ ECE | Δ AURC | CI95 Δ accuracy (seed 0) | CI95 Δ NLL (seed 0) |", "|---|---|---|---|---|---|---|"]
    for key, c in boot["comparisons"].items():
        d, first = c["diff_mean_std_over_seeds"], next(iter(c["per_seed"].values()))["primary"]
        ci = lambda k: f"[{first[k]['ci95'][0]:+.4f}, {first[k]['ci95'][1]:+.4f}]"
        L.append(f"| {key} | " + " | ".join(ms(d[k], 4) for k in ("accuracy", "nll", "ece", "aurc")) + f" | {ci('accuracy')} | {ci('nll')} |")
    # calibration / escalation come from the calibration dirs of the A0 and A3 families
    L += ["", "## Calibration (per-type temperature fitted on calib; temperatures in the order noul / score / choice)", "",
          "| run | T noul | T score | T choice | test ECE before | test ECE after | test NLL before | test NLL after |", "|---|---|---|---|---|---|---|---|"]
    esc_rows = []
    runs = os.path.join(out_dir, "runs")
    for fam in ("A2bami", "A2", "A0", "A3", "A3fix", "A3fixS", "A3cfix"):   # families with a calibration dir (post = calibrate); A2 / A2bami rows = the A2+esc rows
        for j in sorted((x for x in manifest["jobs"] if x["method"] == fam), key=lambda x: x["id"]):
            d = os.path.join(runs, j["id"], "calibration")
            if not os.path.isfile(os.path.join(d, "temperatures.json")):
                continue
            t = json.load(open(os.path.join(d, "temperatures.json")))["per_type_nll"]
            cm = json.load(open(os.path.join(d, "calibration_metrics.json")))["test"]
            L.append(f"| {j['id']} | {t['0']:.3f} | {t['1']:.3f} | {t['2']:.3f} | {cm['uncal']['primary']['all']['ece']:.4f} | "
                     f"{cm['pertype']['primary']['all']['ece']:.4f} | {cm['uncal']['primary']['all']['nll']:.4f} | {cm['pertype']['primary']['all']['nll']:.4f} |")
            if fam != "A0" and os.path.isfile(os.path.join(d, "escalation.json")):
                esc_rows.append((j["id"], json.load(open(os.path.join(d, "escalation.json")))))
    L += ["", "## Escalation head (error detection with the head vs the baseline score max_prob; A2+esc / A3 / A3fix runs)", "",
          "| run | split | AUROC head | AUROC max_prob | AURC head | AURC max_prob | sel.acc@0.5 head / max_prob | @0.7 | @0.9 |", "|---|---|---|---|---|---|---|---|---|"]
    for jid, e in esc_rows:
        for sp in ("calib_oof", "dev", "test"):
            x, h, b = e[sp], e[sp]["selective_head"], e[sp]["selective_max_prob"]
            L.append(f"| {jid} | {sp} | {x['auroc_head']:.4f} | {x['auroc_max_prob']:.4f} | {h['aurc']:.4f} | {b['aurc']:.4f} | "
                     f"{h['sel_acc@0.5']:.4f} / {b['sel_acc@0.5']:.4f} | {h['sel_acc@0.7']:.4f} / {b['sel_acc@0.7']:.4f} | {h['sel_acc@0.9']:.4f} / {b['sel_acc@0.9']:.4f} |")
    L += ["", "## Efficiency (parameters and batch-1 FLOPs of the TRAINED model only: the frozen vision / text encoders are NOT in these rows, see the on-device rows below; latency is measured on a local CPU, not on Kaggle)", "",
          "| model | encoder params | head params | total params | fp32 MB | fp16 MB | FLOPs (batch 1) |", "|---|---|---|---|---|---|---|"]
    for arch, e in eff.items():
        p = e["params"]
        L.append(f"| {arch} | {p['encoder']:,} | {p['heads_and_classifier']:,} | {p['total']:,} | {p['checkpoint_mb_fp32']} | {p['checkpoint_mb_fp16']} | {e['flops_batch1']:.4e} |")
    info = os.path.join(out_dir, "env_info.json")
    if os.path.isfile(info):
        ei = json.load(open(info))
        L += ["", "## Environment", "", f"- torch {ei.get('torch')}, CUDA {ei.get('cuda')}, GPUs {ei.get('gpus')}, code sha256 `{ei.get('code_sha256', '')[:16]}…`",
              f"- S1 sha256: " + ", ".join(f"{k} `{v[:12]}…`" for k, v in ei.get("s1_sha256", {}).items()), "- GPU runs are not bit-exact; the CPU determinism test is the reference."]
    return "\n".join(L) + "\n"


def mean_std_vals(vals):
    import statistics
    vals = [v for v in vals if v is not None and v == v]
    if not vals:
        return {"mean": None, "std": None, "n": 0}
    return {"mean": statistics.mean(vals), "std": statistics.stdev(vals) if len(vals) > 1 else None, "n": len(vals)}


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", nargs="+", required=True)
    ap.add_argument("--split", default="test")
    ap.add_argument("--s1-dir", default=os.path.join(REPO, "..", "vivqa_s1_v2", "data"))
    ap.add_argument("--view", choices=("all", "core", "image_unseen"), default="all")
    ap.add_argument("--flags", help="eval_flags.jsonl (default <s1-dir>/eval_flags.jsonl)")
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)
    gold_full = {it["id"]: it for it in read_jsonl(os.path.join(args.s1_dir, f"{args.split}.jsonl"))}
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import viso_bootstrap
    try:
        gold, view_info = viso_bootstrap.select_view(gold_full, args.s1_dir, args.view, args.flags)
    except (FileNotFoundError, ImportError) as e:
        ap.error(str(e))
    lines = [f"# ViSO results on ViVQA-S1 `{args.split}` (generated by scripts/viso_report.py)", "",
             "| run | n | acc | brier | nll | ece | aurc | noul acc | score acc | choice acc | score rps | S1-Human soft acc | S1-Human KL |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    raw = {}
    for spec in args.runs:
        name, rest = spec.split("=", 1)
        run_dir, _, variant = rest.partition(":")
        path = (os.path.join(run_dir, "calibration", f"preds_{args.split}_{variant}.jsonl") if variant
                else os.path.join(run_dir, f"preds_{args.split}.jsonl"))
        preds = {p["id"]: p for p in read_jsonl(path)}
        unknown = [i for i in preds if i not in gold_full]
        if unknown:
            raise KeyError(f"prediction ids missing from the gold split: {unknown[:5]} ...")
        items = [gold[i] for i in preds if i in gold]                  # preds order; a view scores only its own items
        r = evaluate(items, preds)
        raw[name] = {"source": path, "metrics": r}
        a, h = r["primary"], r["s1_human"]
        lines.append(f"| {name} | {a['all']['n']} | {fmt(a['all']['accuracy'])} | {fmt(a['all']['brier'])} | "
                     f"{fmt(a['all']['nll'])} | {fmt(a['all']['ece'])} | {fmt(a['all']['aurc'])} | "
                     f"{fmt(a.get('noul', {}).get('accuracy'))} | {fmt(a.get('score', {}).get('accuracy'))} | "
                     f"{fmt(a.get('choice', {}).get('accuracy'))} | {fmt(a.get('score', {}).get('rps'))} | "
                     f"{fmt(h['all']['soft_accuracy'])} | {fmt(h['all']['kl'])} |")
    if view_info:
        lines += ["", f"View: {view_info['view']} ({view_info['n_gold_view']} of {view_info['n_gold_split']} gold items), flags "
                      f"{view_info['flags_file']} sha256 {view_info['flags_sha256']}"]
    lines += ["", "Sources: " + "; ".join(f"{k} <- {v['source']}" for k, v in raw.items())]
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    with open(os.path.splitext(args.out)[0] + ".json", "w", encoding="utf-8") as f:
        json.dump(raw, f, indent=1, ensure_ascii=False)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
